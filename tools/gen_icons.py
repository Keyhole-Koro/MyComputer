#!/usr/bin/env python3
"""Turn tools/icons.txt into system/MyOS/src/ui/icons.unsafe.mln.

Each icon is 16 x 16 characters, one per pixel: '.' is transparent and any
other character a palette colour. The generated module keeps, for each icon,
one 8-bit coverage (A8) mask per colour it uses, at 16 x 16 for a 1x display
and 32 x 32 for a 2x one, so drawing an icon is one DMA2D mask command per
colour, as drawing a glyph is one (see gen_font.py).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "icons.txt"
TARGET = ROOT / "system" / "MyOS" / "src" / "ui" / "icons.unsafe.mln"
CONTRACT = ROOT / "contracts" / "ui" / "icon.contract.mln"
SIZE = 16


def parse(text: str):
    palette: dict[str, int] = {}
    icons: list[tuple[str, list[str]]] = []
    section = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line or line.startswith("#"):
            continue
        if line == "palette":
            section = "palette"
            continue
        if line.startswith("icon "):
            section = "icon"
            icons.append((line.split()[1], []))
            continue
        if section == "palette":
            char, color = line.split()[:2]
            palette[char] = int(color, 16)
        elif section == "icon":
            icons[-1][1].append(line)
    for name, rows in icons:
        if len(rows) != SIZE or any(len(r) != SIZE for r in rows):
            sys.exit(f"gen_icons: icon {name} is not {SIZE} x {SIZE}")
        for row in rows:
            for c in row:
                if c != "." and c not in palette:
                    sys.exit(f"gen_icons: icon {name} uses {c!r}, which the palette lacks")
    return palette, icons


def contract_names() -> list[str]:
    """The Icon enum's names after NONE, lower-cased, in order."""
    body = CONTRACT.read_text()
    names = re.findall(r"^\s*([A-Z_]+)\s*=\s*(\d+)", body, re.M)
    return [n.lower() for n, v in sorted(names, key=lambda p: int(p[1])) if int(v) > 0]


def mask(rows: list[str], char: str, scale: int) -> list[int]:
    out = []
    for y in range(SIZE * scale):
        for x in range(SIZE * scale):
            out.append(255 if rows[y // scale][x // scale] == char else 0)
    return out


def main() -> int:
    palette, icons = parse(SOURCE.read_text())
    expected = contract_names()
    names = [name for name, _ in icons]
    if names != expected:
        sys.exit(f"gen_icons: icons {names} do not follow the Icon enum {expected}")
    first, colors, offsets, data = [0], [], [], []
    for name, rows in icons:
        used = []
        for row in rows:
            for c in row:
                if c != "." and c not in used:
                    used.append(c)
        for char in used:
            colors.append(palette[char])
            for scale in (1, 2):
                offsets.append(len(data))
                data.extend(mask(rows, char, scale))
        first.append(len(colors))

    def ints(values):
        return ", ".join(str(v) for v in values)

    lines = [
        "namespace icons;",
        "",
        "// GENERATED by tools/gen_icons.py from tools/icons.txt -- do not edit by hand.",
        "//",
        "// The OS's built-in icons, in the order of the Icon enum. Each is a stack of",
        "// one-colour layers; a layer is an 8-bit coverage (A8) mask, 16 x 16 for a 1x",
        "// display and 32 x 32 for a 2x one, so drawing it is one DMA2D mask command.",
        "// draw() hands the masks, which it owns, to graphics.mask_blit.",
        "",
        'import graphics from "graphics.mln";',
        'import str from "@std/text/str.mln";',
        'import { Icon } from "@contracts/ui/icon.contract.mln";',
        "",
        "/** An icon's size in logical pixels. */",
        f"export const i32 SIZE = {SIZE};",
        "",
        f"i32 ICON_COUNT = {len(icons)};",
        "",
        "// Icon i's layers (from 1) are g_first[i - 1] up to g_first[i].",
        f"i32 g_first[{len(first)}] = {{{ints(first)}}};",
        f"i32 g_color[{len(colors)}] = {{{ints(colors)}}};",
        "// Per layer, its 1x mask's offset into g_data, then its 2x mask's.",
        f"i32 g_off[{len(offsets)}] = {{{ints(offsets)}}};",
        f"char g_data[{len(data)}] = {{{ints(data)}}};",
        "",
        "/**",
        " * @param name An icon's lower-case name, as @app(icon = ...) gives it.",
        " * @return The icon, or Icon::APP for a name that is none.",
        " */",
        "@safe",
        "export i32 named(str name) {",
    ]
    for name in names:
        lines.append(f'    if (name == "{name}") {{ return Icon::{name.upper()}; }}')
    lines += [
        "    return Icon::APP;",
        "}",
        "",
        "/**",
        " * Draws an icon, its top left at (x, y).",
        " * @param icon Icon value; NONE and others draw nothing.",
        " * @param x Display X.",
        " * @param y Display Y.",
        " * @param scale UI scale: 1 draws it 16 pixels square, 2 or more 32.",
        " */",
        "@safe",
        "export void draw(i32 icon, i32 x, i32 y, i32 scale) {",
        "    if (icon < 1 || icon > ICON_COUNT) { return; }",
        "    i32 face = scale >= 2 ? 1 : 0;",
        "    i32 size = SIZE << face;",
        "    i32 layer = g_first[icon - 1];",
        "    while (layer < g_first[icon]) {",
        "        i32 at = (i32)(&g_data[0]) + g_off[layer * 2 + face];",
        "        graphics.mask_blit(at, size, x, y, size, size, g_color[layer]);",
        "        layer++;",
        "    }",
        "}",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"gen_icons: {len(icons)} icons, {len(colors)} layers, {len(data)} bytes -> {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
